/**
 * FDV/TVL multiple by category family. A category is a business model, and different
 * models earn different value per locked dollar: vaults and curators charge fees on
 * managed capital, DEXes and perps earn trading fees, stablecoin issuers earn only
 * the spread on reserves. The lookup is by lower-cased substring so a category the
 * snapshot names tomorrow still lands in a family instead of falling through.
 */
const CATEGORY_MULTIPLES: Array<[string, number]> = [
  ['risk curator', 0.5],
  ['onchain capital allocator', 0.5],
  ['prediction market', 0.45],
  ['launchpad', 0.4],
  ['dex', 0.4],
  ['derivative', 0.4],
  ['perpetual', 0.4],
  ['lending', 0.32],
  ['yield aggregator', 0.32],
  ['yield', 0.32],
  ['leveraged farm', 0.32],
  ['liquidity manager', 0.32],
  ['rwa', 0.3],
  ['basis trading', 0.3],
  ['synthetic', 0.3],
  ['restaking', 0.28],
  ['staking pool', 0.28],
  ['collateral', 0.28],
  ['cdp', 0.2],
  ['stablecoin', 0.18],
  ['algo-stable', 0.18],
  ['chain', 0.2],
  ['bridge', 0.12],
  ['payments', 0.35],
  ['insurance', 0.3],
  ['options', 0.35],
];

/** The FDV/TVL multiple for a category, or the 0.25 default for an unnamed one. */
export function categoryMultiple(category: string | null): number {
  const c = (category ?? '').toLowerCase();
  for (const [key, mult] of CATEGORY_MULTIPLES) {
    if (c.includes(key)) return mult;
  }
  return 0.25;
}

