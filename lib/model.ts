// Token Radar's model, version radar-2: one sealed snapshot in, one ranked board out.
//
// The board ranks every protocol that records no token and is not a wrapped, staked or
// bridged product of a token that already trades. The snapshot's watchlist (40 protocols
// at or above the $50M floor) is the floor, never the ceiling: the board also ranks the
// 158 pre-token protocols below the floor, so the radar finds launches early.
//
// Implied value is one function of the snapshot's own figures, the same for every row:
//
//   implied = round( tvl_usd x catMult x growthMult x maturityMult x breadthMult )
//
//   catMult      FDV/TVL multiple by business model (the category DefiLlama records):
//                fee-taking vaults and curators earn the most per dollar locked, DEXes
//                and derivatives next, stablecoin issuers the least. The table is a
//                category prior, never a list of protocol names.
//   growthMult   1 + clamp(change_7d, -50, +150) / 100 x 0.9. A protocol growing
//                fast is worth more per locked dollar than one shrinking; a missing
//                7-day change counts as 0.
//   maturityMult 0.75 + 0.45 x min(age_days, 1460) / 1460. Age is the days since
//                DefiLlama first listed the protocol: the longer a large protocol has
//                run with no token on record, the more pent-up launch value it carries.
//                An unknown listing date uses 365 days.
//   breadthMult  1 + 0.04 x min(chains - 1, 5). A protocol live on more chains has a
//                wider distribution for a future token.
//
// No protocol name is ever special-cased. Live-token protocols are kept apart and shown
// with the market cap the snapshot records, never mixed into the ranking.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

/** The model's constants, as the dashboard states them. */
export interface ModelConstants {
  growth_weight: number;
  growth_floor: number;
  growth_cap: number;
  maturity_floor: number;
  maturity_range: number;
  maturity_days: number;
  unknown_age_days: number;
  breadth_step: number;
  breadth_max_chains: number;
}

export const MODEL: ModelConstants = {
  growth_weight: 0.9,
  growth_floor: -50,
  growth_cap: 150,
  maturity_floor: 0.75,
  maturity_range: 0.45,
  maturity_days: 1460,
  unknown_age_days: 365,
  breadth_step: 0.04,
  breadth_max_chains: 5,
};

